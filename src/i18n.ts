export type MessageKey = keyof typeof arabic;
export type MessageParams = Record<string, string | number>;
let locale: Locale = "en";
export const getLocale = (): Locale => locale;
export function setLocale(value: Locale): void {
  locale = value;
}

export function resolveLocale(saved: string | null, preferred: string): Locale {
  if (saved === "en" || saved === "ar") return saved;
  return preferred.toLowerCase().split(/[-_]/)[0] === "ar" ? "ar" : "en";
}

export function hasTranslation(message: string): message is MessageKey {
  return Object.hasOwn(arabic, message);
}

export function translate(
  message: string,
  language: Locale = locale,
  params: MessageParams = {},
): string {
  const text =
    language === "ar" && hasTranslation(message) ? arabic[message] : message;
  return text.replace(/\{(\w+)\}/g, (match: string, key: string) => {
    const value = params[key];
    return typeof value === "number"
      ? new Intl.NumberFormat(
          language,
          language === "ar" ? { numberingSystem: "arab" } : {},
        ).format(value)
      : (value ?? match);
  });
}

export function normalizePhoneDigits(value: string): string {
  return value.replace(/[٠-٩۰-۹]/g, (digit) =>
    String(digit.charCodeAt(0) - (digit <= "٩" ? 0x0660 : 0x06f0)),
  );
}
